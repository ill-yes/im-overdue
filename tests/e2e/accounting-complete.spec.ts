import { readFile } from 'node:fs/promises';
import { test, expect, chooseWeek, getState, newBlock } from './isolated-fixture';

test('complete account workflow: setup, payout, direct absence, closure and both exports', async ({ page }, testInfo) => {
  await page.goto('/');
  await chooseWeek(page, '2026-09-28');
  await newBlock(page, '2026-09-28', '09:00', '11:00', 'Testarbeit');
  await page.getByRole('link', { name: 'Zeitkonto', exact: true }).click();
  const account = page.getByRole('region', { name: 'Stundenkonto', exact: true });
  const opening = account.locator('.hours-account-opening');
  await opening.getByLabel('Datum', { exact: true }).fill('2026-09-28');
  await opening.getByLabel('Zeit (h:mm)', { exact: true }).fill('18:00');
  await opening.getByRole('button', { name: 'Anfangsbestand speichern', exact: true }).click();
  await expect(account.locator('.hours-account-opening-summary')).toBeVisible();
  await account.getByRole('button', { name: 'Buchung hinzufügen', exact: true }).click();
  const entry = account.locator('.hours-account-editor');
  await entry.getByLabel('Datum', { exact: true }).fill('2026-09-28');
  await entry.getByLabel('Zeit (h:mm)', { exact: true }).fill('8:00');
  await entry.getByLabel('Begründung', { exact: true }).fill('Synthetische Testauszahlung');
  await entry.getByRole('button', { name: 'Änderungen speichern', exact: true }).click();
  await expect(account.locator('.hours-account-balance strong')).toHaveText('+10 h');

  await account.getByRole('button', { name: 'Abwesenheit eintragen', exact: true }).click();
  const absence = page.getByRole('dialog', { name: 'Abwesenheiten', exact: true });
  await absence.getByLabel('Bis einschließlich', { exact: true }).fill('2026-10-02');
  await absence.locator('.absence-bulk').getByRole('checkbox', { name: 'Krankheit füllt Rest', exact: true }).check();
  const wednesday = absence.locator('.absence-day').filter({ hasText: 'Mittwoch, 30. September 2026' });
  await wednesday.getByRole('combobox', { name: /^Urlaub / }).selectOption('0.5');
  await wednesday.getByRole('combobox', { name: /^Freizeitausgleich / }).selectOption('minutes');
  await wednesday.getByRole('spinbutton', { name: /^Minuten / }).fill('120');
  await expect(wednesday.locator('.absence-calculation')).toContainText('−2 h');
  await absence.getByRole('button', { name: 'Abwesenheiten speichern', exact: true }).click();
  await expect(absence).toHaveCount(0);
  await page.getByRole('link', { name: 'Kalender', exact: true }).click();
  await page.getByRole('button', { name: 'Woche abschließen', exact: true }).click();
  const closure = page.getByRole('dialog', { name: 'Woche abschließen', exact: true });
  await expect(closure).toContainText('Keine offenen Hinweise');
  await closure.getByRole('button', { name: 'Woche abschließen', exact: true }).click();
  await expect(closure).toHaveCount(0);
  await page.getByRole('link', { name: 'Zeitkonto', exact: true }).click();
  await expect(account.locator('.hours-account-balance strong')).toHaveText('+8 h');
  await page.screenshot({ path: testInfo.outputPath('complete-account.png'), fullPage: true });

  await account.getByRole('button', { name: 'Stundenzettel', exact: true }).click();
  const sheet = page.getByRole('dialog', { name: 'Stundenzettel exportieren', exact: true });
  await sheet.getByRole('group', { name: 'Zeitraumart' }).getByRole('button', { name: 'Woche', exact: true }).click();
  await sheet.getByLabel('Datum in der Woche', { exact: true }).fill('2026-09-28');
  await expect(sheet.locator('.timesheet-table tfoot')).toContainText('36:00');
  await expect(sheet.getByRole('checkbox', { name: 'Zeitkonto ergänzen', exact: true })).not.toBeChecked();
  const beforeExport = await getState(page);
  const csvEvent = page.waitForEvent('download');
  await sheet.getByRole('button', { name: 'CSV', exact: true }).click();
  const csvPath = testInfo.outputPath('complete-timesheet.csv');
  await (await csvEvent).saveAs(csvPath);
  expect(await readFile(csvPath, 'utf8')).toContain('Krankheit (Minuten)');
  await sheet.getByRole('checkbox', { name: 'Zeitkonto ergänzen', exact: true }).check();
  await expect(sheet.locator('.timesheet-account')).toContainText('+8:00');
  const accountEvent = page.waitForEvent('download');
  await sheet.getByRole('button', { name: 'Zeitkonto-CSV', exact: true }).click();
  const accountPath = testInfo.outputPath('complete-account.csv');
  await (await accountEvent).saveAs(accountPath);
  expect(await readFile(accountPath, 'utf8')).toContain('480');
  await page.screenshot({ path: testInfo.outputPath('complete-export.png'), fullPage: true });
  await page.pdf({ path: testInfo.outputPath('complete-export.pdf'), format: 'A4', printBackground: true });
  expect(await getState(page)).toEqual(beforeExport);
});
